"""
Load test for the Nexus API.

    pip install locust
    locust -f locustfile.py --host http://localhost:8000 \
           --users 100 --spawn-rate 10 --run-time 2m --headless \
           --csv benchmarks/locust

Each simulated user registers, logs in, creates a project, and then mixes
reads (list projects, list tasks) with writes (create task, complete task).
Task creation runs the zero-shot model on the server, so it is weighted
lower than reads and dominates server CPU.
"""
import random
import uuid

from locust import HttpUser, between, task


class NexusUser(HttpUser):
    wait_time = between(0.5, 2.0)

    def on_start(self):
        name = f"load-{uuid.uuid4().hex[:12]}"
        email = f"{name}@example.com"
        password = uuid.uuid4().hex
        self.client.post("/auth/register", json={"email": email, "username": name, "password": password})
        r = self.client.post("/auth/login", json={"email": email, "password": password})
        self.headers = {"Authorization": f"Bearer {r.json()['access_token']}"}
        r = self.client.post("/projects/", json={"name": "Load test"}, headers=self.headers)
        self.project_id = r.json()["id"]
        self.task_ids = []

    @task(5)
    def list_projects(self):
        self.client.get("/projects/", headers=self.headers)

    @task(5)
    def list_tasks(self):
        self.client.get(f"/tasks/{self.project_id}/tasks", headers=self.headers, name="/tasks/[pid]/tasks")

    @task(2)
    def create_task(self):
        title = random.choice(["Fix login bug", "Update docs", "Production outage", "Add dark mode"])
        r = self.client.post(
            f"/tasks/{self.project_id}/tasks",
            json={"title": title, "description": "generated by locust"},
            headers=self.headers,
            name="/tasks/[pid]/tasks (create)",
        )
        if r.ok:
            self.task_ids.append(r.json()["id"])

    @task(1)
    def complete_task(self):
        if self.task_ids:
            tid = random.choice(self.task_ids)
            self.client.patch(
                f"/tasks/{self.project_id}/tasks/{tid}",
                json={"completed": True},
                headers=self.headers,
                name="/tasks/[pid]/tasks/[tid]",
            )
